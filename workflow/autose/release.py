"""Stage 5: push the branch, open or update the PR, wait for CI. No LLM (ADR-001).

The PAT is used only for `git push` and `gh pr create`, so the push triggers CI
and the PR author differs from the reviewer identity (ADR-005, ADR-012).
"""

import re
import shutil
import time

from . import config, gh
from .checks import CheckResult


def release(run, test_file):
    n, branch = run.n, f"{config.BRANCH_PREFIX}{run.n}{run.suffix}"
    tag = f"autose ({run.variant})" if run.suffix else "autose"
    rel = run.out.parent / "release-tree"
    if rel.exists():
        gh.git(["worktree", "remove", "--force", str(rel)], run.work, check=False)
        shutil.rmtree(rel, ignore_errors=True)
    # The branch is rebuilt from the real base commit plus the stored patches, so
    # it contains exactly the checked change and nothing from a killed attempt (ADR-004).
    gh.git(["worktree", "add", "-q", "-B", branch, str(rel), run.base_sha], run.work)
    try:
        for patch in ("diff.patch", "tests.patch"):
            p = run.out / patch
            if p.is_file() and p.read_text().strip():
                gh.git(["apply", "--whitespace=nowarn", str(p)], rel)
        gh.git(["add", "-A"], rel)
        gh.git(["-c", "user.name=autose-bot", "-c", "user.email=autose-bot@users.noreply.github.com",
                "commit", "-q", "-m", f"{tag}: {run.issue['title']} (#{n})\n\nRound {run.round}. "
                f"Generated by the autose workflow: {gh.run_url()}"], rel)
        head = gh.git(["rev-parse", "HEAD"], rel)
        gh.git(["push", "-q", "--force", f"https://github.com/{config.REPO}.git", f"HEAD:refs/heads/{branch}"],
               rel, token=run.pat)
    finally:
        gh.git(["worktree", "remove", "--force", str(rel)], run.work, check=False)

    body = pr_body(run, test_file)
    run.write("pr.md", body)
    existing = gh.api(f"repos/{config.REPO}/pulls?head={config.REPO.split('/')[0]}:{branch}&state=open", run.token)
    if existing:
        number, url = existing[0]["number"], existing[0]["html_url"]
        gh.gh(["pr", "edit", str(number), "--repo", config.REPO, "--body-file", str(run.out / "pr.md")], run.pat)
    else:
        url = gh.gh(["pr", "create", "--repo", config.REPO, "--base", "main", "--head", branch,
                     "--title", f"{tag}: {run.issue['title']} (#{n})", "--body-file", str(run.out / "pr.md")],
                    run.pat).strip()
        number = int(url.rstrip("/").split("/")[-1])
    pr = {"number": number, "url": url, "head_sha": head}
    run.pr = pr
    run.write("pr.md", body + f"\n\n---\nPull request: {url}\nHead commit: `{head}`\n")
    run.progress()
    run.log(f"S5: pushed {branch} at {head[:7]}, PR #{number}")
    ci = wait_for_ci(run, head)
    run.write("pr.md", run.stage_file("pr.md") + "\n## Pipeline check (stage 5, CI)\n\n" + ci.md())
    return pr, ci


def pr_body(run, test_file):
    acs = [l for l in run.stage_file("spec.md").splitlines() if l.strip().startswith("- AC-")]
    return (f"Closes #{run.n}\n\n"
            "This pull request was generated by the **autose** workflow. A person decides whether to merge it.\n\n"
            f"- Workflow run: {gh.run_url()}\n"
            f"- Stage artifacts (spec, design, diff, test report): "
            f"https://github.com/{config.REPO}/tree/{config.STATE_BRANCH}/runs/issue-{run.n}{run.suffix}/round-{run.round}\n"
            f"- New tests: `{test_file}`\n"
            f"- Round: {run.round} of {config.MAX_REVIEW_ROUNDS}\n"
            + (f"- Experiment variant: `{run.variant}` (see `experiment/variants.md`)\n" if run.suffix else "") + "\n"
            "### Acceptance criteria covered\n\n" + "\n".join(acs[:20]) + "\n")


def wait_for_ci(run, head):
    """All check runs on the head commit must finish successfully (ADR-007, stage 5)."""
    deadline = time.time() + config.CI_TIMEOUT
    time.sleep(30)
    stable, last_count = 0, -1
    while time.time() < deadline:
        data = gh.api(f"repos/{config.REPO}/commits/{head}/check-runs?per_page=100", run.token)
        runs = data.get("check_runs", [])
        pending = [c for c in runs if c["status"] != "completed"]
        if runs and not pending:
            stable = stable + 1 if len(runs) == last_count else 0
            if stable >= 1:
                break
        last_count = len(runs)
        time.sleep(20)
    else:
        return CheckResult(False, [f"CI did not finish within {config.CI_TIMEOUT // 60} minutes"])
    bad = [c for c in runs if c["conclusion"] not in ("success", "skipped", "neutral")]
    reasons = [f"{len(runs)} check run(s); failing: {[c['name'] for c in bad] or 'none'}"]
    for c in bad[:3]:
        log = ""
        for tok in (run.token, run.pat):
            log = gh.gh(["api", f"repos/{config.REPO}/actions/jobs/{c['id']}/logs"], tok, check=False)
            if log.strip():
                break
        reasons.append(f"`{c['name']}` ({c['conclusion']}), relevant lines of its log:\n\n```\n{_relevant(log)}\n```")
    return CheckResult(not bad, reasons)


def _relevant(log, limit=2500):
    """The lines that explain a failure, not the job's cleanup at the end (found in run 45011011795)."""
    lines = [re.sub(r"^\S+Z ", "", l) for l in log.splitlines()]
    keep = set()
    for i, l in enumerate(lines):
        if re.search(r"error|fail|misspell|traceback|assert|E\d{3}|F\d{3}|W\d{3}", l, re.I) \
                and "##[group]" not in l and "deprecated" not in l:
            keep.update(range(max(0, i - 3), min(len(lines), i + 8)))
    text = "\n".join(lines[i] for i in sorted(keep)) or "\n".join(lines[-40:])
    return text[:limit] or "(log not available)"
